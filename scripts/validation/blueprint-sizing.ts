// Real pointer/keyboard validation against the isolated local Firebase provider.
import assert from 'node:assert/strict';
export async function validateBlueprintSizing(page: any, base: string) {
  const saved = async () => (await (await fetch(base + '/api/vaccine/blueprint-districts/validation-sheet/current', { headers: { Authorization: 'Bearer validation-token:0' } })).json()).sheet;
  const saveAction = async (action: () => Promise<any>) => {
    const response = page.waitForResponse((response: any) => response.url().endsWith('/api/vaccine/blueprint-districts') && response.request().method() === 'POST');
    response.catch(() => {}); await action(); assert.equal((await response).status(), 200);
  };
  const drag = async (handle: any, dx: number, dy: number) => {
    await handle.scrollIntoViewIfNeeded(); const box = await handle.boundingBox();
    const x = box.x + box.width / 2, y = box.y + box.height / 2;
    await page.mouse.move(x, y); await page.mouse.down();
    await page.mouse.move(x + dx, y + dy, { steps: 5 }); await page.mouse.up();
  };
  let sheet = await saved();
  const original = sheet.rows.find((row: any) => row.id === 'validation-row');
  const originalVaccines = JSON.stringify(original.vaccines);
  const columnA = page.getByRole('separator', { name: 'Resize column A', exact: true });
  const columnB = page.getByRole('separator', { name: 'Resize column B', exact: true });
  const originalBWidth = (await columnB.locator('..').boundingBox()).width;
  await saveAction(() => drag(columnA, 60, 0));
  assert.equal((await saved()).sheetSizing.columnWidths['field:processing'], 200);
  assert.ok(Math.abs((await columnA.locator('..').boundingBox()).width - 200) < 2);
  assert.ok(Math.abs((await columnB.locator('..').boundingBox()).width - originalBWidth) < 2, 'Adjacent columns must not be resized');
  await saveAction(() => drag(columnA, -90, 0));
  assert.equal((await saved()).sheetSizing.columnWidths['field:processing'], 110);
  assert.ok(Math.abs((await columnA.locator('..').boundingBox()).width - 110) < 2, 'Columns must shrink below their original minimum');
  const rowNumber = sheet.rows.findIndex((row: any) => row.id === 'validation-row') + 5;
  const rowHandle = page.getByRole('separator', { name: `Resize row ${rowNumber}`, exact: true });
  const oldHeight = (await rowHandle.locator('xpath=ancestor::tr').boundingBox()).height;
  await saveAction(() => drag(rowHandle, 0, 40));
  const tall = (await saved()).sheetSizing.rowHeights['validation-row'];
  assert.ok(Math.abs(tall - oldHeight - 40) < 2);
  assert.ok(Math.abs((await rowHandle.locator('xpath=ancestor::tr').boundingBox()).height - tall) < 2);
  await saveAction(() => drag(rowHandle, 0, -30));
  const short = (await saved()).sheetSizing.rowHeights['validation-row'];
  assert.equal(short, tall - 30);
  assert.ok(Math.abs((await rowHandle.locator('xpath=ancestor::tr').boundingBox()).height - short) < 2);
  const blank = sheet.blankColumns[0], baseCount = 5 + sheet.products.length * 4;
  const blankHandle = page.locator(`thead tr[data-sheet-row-index="4"] [data-grid-cell-col="${baseCount}"] [role="separator"][aria-orientation="vertical"]`);
  await saveAction(() => drag(blankHandle, 40, 0));
  assert.equal((await saved()).sheetSizing.columnWidths[`blank:${blank.id}`], 160);
  const blankRowId = sheet.rows[0].id;
  const blankRowHandle = page.getByRole('separator', { name: 'Resize row 5', exact: true });
  await saveAction(() => drag(blankRowHandle, 0, 20));
  assert.ok((await saved()).sheetSizing.rowHeights[blankRowId] > 32);
  await page.getByLabel('Spreadsheet zoom').selectOption('150');
  await saveAction(() => drag(columnA, 30, 0));
  assert.equal((await saved()).sheetSizing.columnWidths['field:processing'], 130, 'Resize should account for zoom');
  await page.getByLabel('Spreadsheet zoom').selectOption('100');
  await saveAction(() => page.getByTitle('Undo', { exact: true }).click());
  assert.equal((await saved()).sheetSizing.columnWidths['field:processing'], 110, 'One complete drag must be one undo step');
  await saveAction(() => page.getByTitle('Redo', { exact: true }).click());
  assert.equal((await saved()).sheetSizing.columnWidths['field:processing'], 130);
  await page.getByRole('button', { name: 'Full screen', exact: true }).click();
  await saveAction(() => columnA.press('ArrowRight'));
  await page.keyboard.press('Escape');
  assert.equal((await saved()).sheetSizing.columnWidths['field:processing'], 140);
  // Resize directly from an ordinary facility cell, away from the header and row handle.
  const cellWidth = page.getByRole('separator', { name: `Resize cell C${rowNumber} width`, exact: true });
  const cellHeight = page.getByRole('separator', { name: `Resize cell C${rowNumber} height`, exact: true });
  await saveAction(() => drag(cellWidth, 50, 0));
  assert.equal((await saved()).sheetSizing.columnWidths['field:facility'], 280);
  await saveAction(() => drag(cellWidth, -30, 0));
  assert.equal((await saved()).sheetSizing.columnWidths['field:facility'], 250);
  assert.ok(Math.abs((await cellWidth.locator('..').boundingBox()).width - 250) < 2);
  await saveAction(() => drag(cellHeight, 0, 20));
  assert.equal((await saved()).sheetSizing.rowHeights['validation-row'], short + 20);
  await saveAction(() => drag(cellHeight, 0, -10));
  assert.equal((await saved()).sheetSizing.rowHeights['validation-row'], short + 10);
  assert.ok(Math.abs((await cellHeight.locator('xpath=ancestor::tr').boundingBox()).height - short - 10) < 2);
  await page.reload(); await page.getByRole('button', { name: /^Allocation Blueprint/ }).click(); await columnA.waitFor();
  sheet = await saved();
  assert.equal(sheet.sheetSizing.columnWidths['field:processing'], 140);
  assert.equal(sheet.sheetSizing.columnWidths['field:facility'], 250);
  assert.equal(sheet.sheetSizing.rowHeights['validation-row'], short + 10);
  assert.equal(sheet.sheetSizing.columnWidths[`blank:${blank.id}`], 160);
  assert.ok(Math.abs((await columnA.locator('..').boundingBox()).width - 140) < 2);
  assert.equal(JSON.stringify(sheet.rows.find((row: any) => row.id === 'validation-row').vaccines), originalVaccines);
  return { directCellBorders: true, growAndShrinkColumns: true, growAndShrinkRows: true, independentColumnWidths: true, blankColumnAndRow: true, zoomAware: true, singleStepUndoRedo: true, fullscreenKeyboardResize: true, persistedAfterReload: true, originalAllocationsPreserved: true };
}
